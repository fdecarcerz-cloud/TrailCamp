CREATE OR REPLACE FUNCTION public.aceptar_invitacion(p_token uuid)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_uid uuid := (select auth.uid());
  v_email text := (select auth.jwt()) ->> 'email';
  v_part public.participants%rowtype;
  v_otro text;
begin
  if v_uid is null then
    raise exception 'Inicia sesión para aceptar la invitación.';
  end if;

  select * into v_part from public.participants where invite_token = p_token;
  if not found then
    raise exception 'Este link de invitación no es válido. Pídele uno nuevo a quien te invitó.';
  end if;

  if v_part.user_id = v_uid then
    return v_part.trip_id;
  end if;
  if v_part.user_id is not null then
    raise exception 'Esta invitación ya la usó otra cuenta. Pídele a quien te invitó que lo revise.';
  end if;

  select name into v_otro from public.participants
  where trip_id = v_part.trip_id and id <> v_part.id
    and (user_id = v_uid or lower(email) = lower(v_email))
  limit 1;
  if found then
    raise exception 'Ya estás en este viaje como "%".', v_otro;
  end if;

  -- El correo pasa a ser el de la cuenta, para que la app lo muestre y lo reconozca
  update public.participants
  set user_id = v_uid,
      email = coalesce(v_email, email)
  where id = v_part.id;

  return v_part.trip_id;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.borrar_participante(p_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare
  v_nombre text;
  v_viaje bigint;
  v_gastos int;
begin
  select name, trip_id into v_nombre, v_viaje from public.participants where id = p_id;
  if not found then
    raise exception 'No se encontró a esa persona en el equipo.';
  end if;
  if not public.es_creador_viaje(v_viaje) then
    raise exception 'Solo el creador del viaje puede borrar personas del equipo.';
  end if;

  select count(*) into v_gastos from public.expenses
  where trip_id = v_viaje and (paid_by = v_nombre or v_nombre = any(split_between));

  if v_gastos > 0 then
    raise exception '% aparece en %. Edita o borra esos gastos primero, para que las cuentas no queden mal.',
      v_nombre,
      case when v_gastos = 1 then '1 gasto o pago' else v_gastos || ' gastos o pagos' end;
  end if;

  if exists (select 1 from public.carpools where trip_id = v_viaje and driver_name = v_nombre) then
    raise exception '% maneja un auto en este viaje. Cambia el conductor o borra ese auto primero.', v_nombre;
  end if;

  update public.gear
  set assigned_to = null,
      status = case when status = 'Asignado' then 'Pendiente' else status end
  where trip_id = v_viaje and assigned_to = v_nombre;

  update public.carpools set passengers = array_remove(passengers, v_nombre)
  where trip_id = v_viaje and v_nombre = any(passengers);

  delete from public.participants where id = p_id;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.es_creador_viaje(viaje_id bigint)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select exists (
    select 1 from public.trips t
    where t.id = viaje_id and t.user_id = (select auth.uid())
  );
$function$
;

CREATE OR REPLACE FUNCTION public.guardar_notas_viaje(p_viaje bigint, p_notas text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if not public.puede_ver_viaje(p_viaje) then
    raise exception 'No tienes acceso a este viaje.';
  end if;
  if length(coalesce(p_notas, '')) > 5000 then
    raise exception 'Las notas pueden tener como máximo 5.000 caracteres.';
  end if;

  update public.trips
  set description = nullif(btrim(coalesce(p_notas, '')), '')
  where id = p_viaje;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.participante_nuevo_seguro()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
begin
  new.invite_token := gen_random_uuid();
  if new.user_id is distinct from (select auth.uid()) then
    new.user_id := null;
  end if;
  return new;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.puede_ver_boleta(ruta text)
 RETURNS boolean
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
  select case
    when (storage.foldername(ruta))[1] ~ '^[0-9]+$'
      then public.puede_ver_viaje(((storage.foldername(ruta))[1])::bigint)
    else false
  end;
$function$
;

CREATE OR REPLACE FUNCTION public.puede_ver_viaje(viaje_id bigint)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select exists (
    select 1 from public.trips t
    where t.id = viaje_id and t.user_id = (select auth.uid())
  ) or exists (
    select 1 from public.participants p
    where p.trip_id = viaje_id
      and (p.user_id = (select auth.uid())
        or lower(p.email) = lower((select auth.jwt()) ->> 'email'))
  );
$function$
;

CREATE OR REPLACE FUNCTION public.renombrar_participante(p_id bigint, p_nombre text, p_email text, p_rol text, p_telefono text DEFAULT NULL::text)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare
  v_viejo text;
  v_viaje bigint;
  v_nuevo text := btrim(coalesce(p_nombre, ''));
begin
  if v_nuevo = '' then
    raise exception 'El nombre no puede quedar vacío.';
  end if;

  select name, trip_id into v_viejo, v_viaje from public.participants where id = p_id;
  if not found then
    raise exception 'No se encontró a esa persona en el equipo.';
  end if;
  if not public.es_creador_viaje(v_viaje) then
    raise exception 'Solo el creador del viaje puede editar el equipo.';
  end if;

  update public.participants
  set name = v_nuevo,
      email = nullif(btrim(coalesce(p_email, '')), ''),
      phone = case when p_telefono is null then phone else nullif(btrim(p_telefono), '') end,
      role = p_rol
  where id = p_id;

  if v_viejo is distinct from v_nuevo then
    update public.gear set assigned_to = v_nuevo
    where trip_id = v_viaje and assigned_to = v_viejo;

    update public.carpools set driver_name = v_nuevo
    where trip_id = v_viaje and driver_name = v_viejo;

    update public.carpools set passengers = array_replace(passengers, v_viejo, v_nuevo)
    where trip_id = v_viaje and v_viejo = any(passengers);

    update public.expenses set paid_by = v_nuevo
    where trip_id = v_viaje and paid_by = v_viejo;

    update public.expenses set split_between = array_replace(split_between, v_viejo, v_nuevo)
    where trip_id = v_viaje and v_viejo = any(split_between);

    update public.expenses set description = 'Pago de ' || paid_by || ' a ' || split_between[1]
    where trip_id = v_viaje and is_settlement;
  end if;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.sync_trip_legacy_dates()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
  IF NEW.start_date IS NOT NULL AND NEW.date IS NULL THEN
    NEW.date := NEW.start_date;
  END IF;
  RETURN NEW;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.sync_trip_title_name()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
  IF NEW.name IS NOT NULL AND NEW.title IS NULL THEN
    NEW.title := NEW.name;
  ELSIF NEW.title IS NOT NULL AND NEW.name IS NULL THEN
    NEW.name := NEW.title;
  END IF;
  RETURN NEW;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.ver_invitacion(p_token uuid)
 RETURNS TABLE(trip_id bigint, viaje text, destino text, inicio text, fin text, nombre text, ocupada boolean, es_mia boolean)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select t.id, t.name, t.destination, t.start_date, t.end_date, p.name,
    p.user_id is not null,
    p.user_id is not null and p.user_id = (select auth.uid())
  from public.participants p
  join public.trips t on t.id = p.trip_id
  where p.invite_token = p_token;
$function$
;

