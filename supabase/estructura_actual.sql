create table if not exists public.carpools (
  id bigint generated by default as identity not null,
  trip_id bigint not null,
  driver text,
  car text,
  total_seats integer default 4,
  passengers text[] default ARRAY[]::text[],
  meeting_point text,
  created_at timestamp with time zone default timezone('utc'::text, now()),
  driver_name text,
  departure_location text,
  departure_time text,
  seats_available integer default 3
);

create table if not exists public.expenses (
  id bigint generated by default as identity not null,
  trip_id bigint not null,
  description text,
  amount integer,
  paid_by text,
  included_members text[],
  created_at timestamp with time zone default timezone('utc'::text, now()),
  split_between text[] default '{}'::text[],
  is_settlement boolean default false not null
);

create table if not exists public.gear (
  id bigint generated by default as identity not null,
  trip_id bigint not null,
  item text,
  quantity integer default 1 not null,
  priority text default 'Importante'::text not null,
  assigned_to text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  name text,
  status text default 'Pendiente'::text not null
);

create table if not exists public.participants (
  id bigint generated by default as identity not null,
  trip_id bigint not null,
  name text not null,
  role text default 'Participante'::text not null,
  status text default 'Pendiente'::text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  email text
);

create table if not exists public.trips (
  id bigint generated by default as identity not null,
  title text,
  destination text,
  date text,
  created_at timestamp with time zone default timezone('utc'::text, now()),
  end_date text,
  start_date text,
  name text,
  description text,
  user_id uuid
);

