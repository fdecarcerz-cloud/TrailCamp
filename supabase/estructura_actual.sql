CREATE OR REPLACE FUNCTION public.puede_ver_viaje(viaje_id bigint)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select exists (
    select 1 from public.trips t
    where t.id = viaje_id and t.user_id = (select auth.uid())
  ) or exists (
    select 1 from public.participants p
    where p.trip_id = viaje_id
      and lower(p.email) = lower((select auth.jwt()) ->> 'email')
  );
$function$
;

CREATE OR REPLACE FUNCTION public.sync_trip_legacy_dates()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
  IF NEW.start_date IS NOT NULL AND NEW.date IS NULL THEN
    NEW.date := NEW.start_date;
  END IF;
  RETURN NEW;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.sync_trip_title_name()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
  IF NEW.name IS NOT NULL AND NEW.title IS NULL THEN
    NEW.title := NEW.name;
  ELSIF NEW.title IS NOT NULL AND NEW.name IS NULL THEN
    NEW.name := NEW.title;
  END IF;
  RETURN NEW;
END;
$function$
;

CREATE TRIGGER trg_sync_trip_legacy_dates BEFORE INSERT OR UPDATE ON public.trips FOR EACH ROW EXECUTE FUNCTION sync_trip_legacy_dates();

CREATE TRIGGER trg_sync_trip_title_name BEFORE INSERT OR UPDATE ON public.trips FOR EACH ROW EXECUTE FUNCTION sync_trip_title_name();

