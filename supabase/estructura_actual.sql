CREATE OR REPLACE FUNCTION public.guardar_notas_viaje(p_viaje bigint, p_notas text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if not public.puede_ver_viaje(p_viaje) then
    raise exception 'No tienes acceso a este viaje.';
  end if;
  if length(coalesce(p_notas, '')) > 5000 then
    raise exception 'Las notas pueden tener como máximo 5.000 caracteres.';
  end if;

  update public.trips
  set description = nullif(btrim(coalesce(p_notas, '')), '')
  where id = p_viaje;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.guardar_ubicacion_viaje(p_viaje bigint, p_lat double precision, p_lon double precision, p_lugar text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if not public.puede_ver_viaje(p_viaje) then
    raise exception 'No tienes acceso a este viaje.';
  end if;
  if p_lat is null or p_lon is null or p_lat not between -90 and 90 or p_lon not between -180 and 180 then
    raise exception 'La ubicación no es válida.';
  end if;

  update public.trips
  set latitude = p_lat,
      longitude = p_lon,
      place_label = left(nullif(btrim(coalesce(p_lugar, '')), ''), 200)
  where id = p_viaje;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.limpiar_ubicacion_viaje()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
begin
  if new.destination is distinct from old.destination
     and new.latitude is not distinct from old.latitude
     and new.longitude is not distinct from old.longitude then
    new.latitude := null;
    new.longitude := null;
    new.place_label := null;
  end if;
  return new;
end;
$function$
;

