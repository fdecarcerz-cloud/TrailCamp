CREATE OR REPLACE FUNCTION public.aceptar_invitacion(p_token uuid)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_uid uuid := (select auth.uid());
  v_email text := (select auth.jwt()) ->> 'email';
  v_part public.participants%rowtype;
  v_otro text;
begin
  if v_uid is null then
    raise exception 'Inicia sesión para aceptar la invitación.';
  end if;

  select * into v_part from public.participants where invite_token = p_token;
  if not found then
    raise exception 'Este link de invitación no es válido. Pídele uno nuevo a quien te invitó.';
  end if;

  if v_part.user_id = v_uid then
    return v_part.trip_id;
  end if;
  if v_part.user_id is not null then
    raise exception 'Esta invitación ya la usó otra cuenta. Pídele a quien te invitó que lo revise.';
  end if;

  select name into v_otro from public.participants
  where trip_id = v_part.trip_id and id <> v_part.id
    and (user_id = v_uid or lower(email) = lower(v_email))
  limit 1;
  if found then
    raise exception 'Ya estás en este viaje como "%".', v_otro;
  end if;

  -- El correo pasa a ser el de la cuenta, para que la app lo muestre y lo reconozca
  update public.participants
  set user_id = v_uid,
      email = coalesce(v_email, email)
  where id = v_part.id;

  return v_part.trip_id;
end;
$function$
;

create or replace function public.borrar_participante(p_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_nombre text;
  v_viaje bigint;
  v_gastos int;
  v_papelera int;
  v_texto text;
begin
  select name, trip_id into v_nombre, v_viaje from public.participants where id = p_id;
  if not found then
    raise exception 'No se encontró a esa persona en el equipo.';
  end if;
  if not public.es_creador_viaje(v_viaje) then
    raise exception 'Solo el creador del viaje puede borrar personas del equipo.';
  end if;

  select count(*) filter (where deleted_at is null), count(*) filter (where deleted_at is not null)
  into v_gastos, v_papelera
  from public.expenses
  where trip_id = v_viaje and (paid_by = v_nombre or v_nombre = any(split_between));

  if v_gastos > 0 then
    v_texto := format('%s aparece en %s. Edita o borra esos gastos primero, para que las cuentas no queden mal.',
      v_nombre,
      case when v_gastos = 1 then '1 gasto o pago' else v_gastos || ' gastos o pagos' end);
    if v_papelera > 0 then
      v_texto := v_texto || format(' También aparece en %s de la papelera.', v_papelera);
    end if;
    raise exception '%', v_texto;
  end if;
  if v_papelera > 0 then
    raise exception '% aparece en % de la papelera. Bórralos definitivamente desde la papelera de Gastos primero.',
      v_nombre,
      case when v_papelera = 1 then '1 gasto o pago' else v_papelera || ' gastos o pagos' end;
  end if;

  if exists (select 1 from public.carpools where trip_id = v_viaje and driver_name = v_nombre) then
    raise exception '% maneja un auto en este viaje. Cambia el conductor o borra ese auto primero.', v_nombre;
  end if;

  update public.gear
  set assigned_to = null,
      status = case when status = 'Asignado' then 'Pendiente' else status end
  where trip_id = v_viaje and assigned_to = v_nombre;

  update public.carpools set passengers = array_remove(passengers, v_nombre)
  where trip_id = v_viaje and v_nombre = any(passengers);

  delete from public.participants where id = p_id;
end;
$$;

create or replace function public.crear_viaje(
  p_tipo text,
  p_nombre text,
  p_destino text,
  p_inicio text,
  p_fin text,
  p_lat double precision,
  p_lon double precision,
  p_lugar text,
  p_mi_nombre text
)
returns bigint
language plpgsql
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_email text := (select auth.jwt()) ->> 'email';
  v_nombre text := btrim(coalesce(p_nombre, ''));
  v_destino text := nullif(btrim(coalesce(p_destino, '')), '');
  v_inicio text := nullif(btrim(coalesce(p_inicio, '')), '');
  v_fin text := nullif(btrim(coalesce(p_fin, '')), '');
  v_yo text := nullif(btrim(coalesce(p_mi_nombre, '')), '');
  v_viaje bigint;
begin
  if v_uid is null then
    raise exception 'Inicia sesión para crear un viaje.';
  end if;
  if v_nombre = '' then
    raise exception 'Escribe un nombre.';
  end if;
  if coalesce(p_tipo, 'viaje') not in ('viaje', 'gastos') then
    raise exception 'Tipo de viaje no válido.';
  end if;

  -- Con una sola fecha, el viaje es de un día
  v_inicio := coalesce(v_inicio, v_fin);
  v_fin := coalesce(v_fin, v_inicio);
  if v_inicio is not null and v_inicio !~ '^\d{4}-\d{2}-\d{2}$' or v_fin is not null and v_fin !~ '^\d{4}-\d{2}-\d{2}$' then
    raise exception 'Las fechas no son válidas.';
  end if;
  if v_fin < v_inicio then
    raise exception 'La fecha de término no puede ser antes de la fecha de inicio.';
  end if;
  if coalesce(p_tipo, 'viaje') = 'viaje' and (v_destino is null or v_inicio is null) then
    raise exception 'Un viaje necesita destino y fechas.';
  end if;

  insert into public.trips (kind, name, destination, start_date, end_date, latitude, longitude, place_label, user_id)
  values (
    coalesce(p_tipo, 'viaje'), v_nombre, v_destino, v_inicio, v_fin, p_lat, p_lon,
    case when p_lat is null then null else left(nullif(btrim(coalesce(p_lugar, '')), ''), 200) end,
    v_uid
  )
  returning id into v_viaje;

  -- El creador entra como Organizador con su nombre de "Mi cuenta" (o el comienzo del correo)
  insert into public.participants (trip_id, name, email, user_id, role, status)
  values (
    v_viaje,
    coalesce(v_yo, nullif(split_part(coalesce(v_email, ''), '@', 1), ''), 'Organizador'),
    v_email,
    v_uid,
    'Organizador',
    'Confirmado'
  );

  return v_viaje;
end;
$$;

create or replace function public.bloquear_autos_viaje(p_viaje bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.puede_ver_viaje(p_viaje) then
    raise exception 'No tienes acceso a este viaje.';
  end if;
